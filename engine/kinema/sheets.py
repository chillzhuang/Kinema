def figure_proportions() -> str:
    """全身立像的人体比例契约（角色定稿表与动作表共用）。

    决定腿长的是胯线高度，不是头的份数：只给头身比时模型按训练集均值落笔，
    胯线掉到全高 0.56~0.59、腿长只剩四成。**写实档的角色设定图走纯文生图、
    不垫版式蓝图**（见 `docs/agents/photoreal-face.md`），那一档控制人体比例的
    通道只有这段文字，故按转面表的做法逐段给出**可数的分段高度**——
    「八头身」是一个总量声明，模型对它的响应远弱于一串能数的段落。
    """
    return ("**全身立像按八头身标准人体比例绘制（eight-head canon）：以头高为单位"
            "自上而下分六段——头顶到下巴 1 头，下巴到乳线 1 头，乳线到脐 1 头，"
            "脐到胯线（裆部）1 头，胯线到膝 2 头，膝到脚底 2 头；由此胯线正落在"
            "头顶到脚底的正中，可略高绝不可低，肩线在头顶下约一又四分之一头，"
            "颈根到胯线的躯干与胯线到脚底的腿长之比约 3:4，腿长占全高一半；"
            "绝不把胯线画到全高一半以下，绝不画成躯干长、腿短的体型**"
            "（角色设定显式写明儿童、Q 版等特殊体型时按设定执行）")


def char_rules() -> list[str]:
    """角色设定图的版式纪律（生成与改造共用的那一段）。

    版式（对齐视频侧官方人物参考建议「大头照 + 全身照即可，不建议人物多视图——
    多视图易被识别为多个不同主体，反而加剧 ID 漂移」；侧视是漂移风险最高、信息
    增量最低的一视，不设）：横向三区、宽度比约 40% : 30% : 30%，只靠留白分区——
    左区=锁骨以上正面肖像大特写（锁五官/瞳色/发型，中性表情嘴唇轻闭——表情戏留给
    分镜，定稿表用中性脸）；中区/右区=同一角色的正面与背面全身立像，同地平线等高
    等比。武器与随身物件不上本表（走独立的道具/武器设定图，一张参考一个职责）。
    """
    return [
        "角色设定图 character model sheet（动画工业定稿版式，一张表锁死该角色全部视觉锚点）",
        figure_proportions(),
        # 分区靠留白而非画线：模型一旦获准画栏框，就会顺手把栏框升级成带标题栏的
        # 表格边框——那是被禁的文字层的入口
        "版面横向划分为三个内容区，宽度比例约 40% : 30% : 30%，三区各自居中、"
        "内容互不重叠；分区只由统一留白与对齐关系表达，"
        "**不画任何竖向分隔线、竖线或实线栏框**",
        "左区（约占画面宽度四成）：锁骨以上正面肖像大特写（正面朝向，"
        "**中性自然表情、嘴唇轻闭不露齿、不做夸张笑容**——表情属于分镜，定稿肖像用中性脸，"
        "头部、颈部与锁骨完整可见，锁骨以下不出现胸部、躯干或完整肩臂，"
        # 取景裁到锁骨是构图语句、不是着装语句：缺一句正面着装要求时，
        # 「不出现肩臂」会被执行成裸肩画到画框边、只悬一圈衣领
        "**肖像穿着与全身像完全相同的服装：领口、衣领与被取景截到的肩线照常入画，"
        "绝不画成裸肩、裸上身或只悬一圈衣领**，"
        "头顶到画面上缘留出约本区高度一成的空白，"
        "放大展示五官结构、眼型与瞳色高光、眉形、发际线与发流走向、肤质，锁死面部锚点）",
        "中区与右区各居中放置同一角色的一个全身立像——**中区正面、右区背面**，"
        "两像站在同一条地平线、底部对齐、等高等比例，"
        "人像高度约占本区高度八成五、脚底留出地面空白",
        "中性 A 字站姿、双臂微离躯干露出完整剪影，面部与肖像同为中性放松表情，"
        "**仅穿戴完整服装、双手空手，不持握、不佩戴、不背挂任何武器或道具**"
        "（武器与随身物件一律走各自独立的设定图，不出现在本表上），"
        "服装衣纹、配色与体积结构逐视图交代完整——背面像如实交代后背服装结构、"
        "发型背面与披风等背部服饰；"
        "两像之间的间距与它们各自到画面外缘的留白目视相等，"
        "不加竖线、分割线或标题文字",
    ]


def char_tail() -> list[str]:
    """角色设定图的收尾段（一致性 + 版面），与 `char_rules` 同属版式纪律。"""
    return [
        # 头身比只在两个全身像之间才可比：肖像取景到锁骨，没有身可比
        "肖像与两个全身视图之间五官、发色瞳色与服装（含衣领与领口样式）严格一致，"
        "两个全身视图之间头身比与体型完全一致，线条干净利落，上色平整考究",
        "正交平视视角，均匀漫射柔光无投影，纯色浅灰无缝底（单一浅灰无渐变，"
        "不加地台、投影盘、网格或标尺），专业角色设计定稿排版，"
        "疏朗留白、信息密度高而不乱，无场景干扰；"
        # 三区之外不许长出多余构件：本表不设色板与细节格槽位，模型照设定集
        # 惯例补一条就是在挤占三区留白
        "**画面上不出现色板色块、细节小格或任何局部放大小图**；"
        "整张图是完整的纯图片设定图，**禁止任何文字、标题、简介、信息栏、编号、数字、"
        "logo、水印或签名**",
    ]


def char_sheet_prompt(c: dict, prefix: str, *, n_templates: int = 0) -> str:
    """角色设定图完整提示词（`project refs` 出图用）。`n_templates` = 实附样板张数
    （0 = 未附，不注入职责声明——声明了却没附，就是向模型索要不存在的参考；
    写实档纯文生图恒传 0）。

    角色清单只取 `silhouette_notes` 一项，插在 appearance 之后——剪影特征是跨镜
    一致性的强锚点，与三区两视版式同向。**`constraints` 刻意不进本提示词**：它是用户
    自由文本禁令，会与引擎铁律（全身空手 / 无场景无文字）正面竞争甚至自相矛盾
    （写「必须持剑」直接顶撞「全身空手」）；其落点在分镜侧的 `shots[].negative_prompt`。
    """
    parts = [prefix,
             # 紧跟画风前缀，见其定义处
             (template_role("character") if n_templates else ""),
             *char_rules(),
             c.get("appearance") or c.get("name") or "",
             (f"剪影辨识度要点（结构特征必须画准，全黑剪影也要一眼认出是他）："
              f"{c['silhouette_notes']}" if c.get("silhouette_notes") else ""),
             (f"必须画出的视觉特征（下游每一镜都按它核对身份）："
              f"{'；'.join(str(v).strip() for v in c['visual_requirements'] if str(v).strip())}"
              if c.get("visual_requirements") else ""),
             (f"角色定位与气质：{c['role']}" if c.get("role") else ""),
             (f"服装：{c['outfit']}" if c.get("outfit") else ""),
             (f"发型：{c['hair']}" if c.get("hair") else ""),
             *char_tail()]
    return join_prompt(parts)


# ---------------------------------------------------------------------------
# 二、道具 / 武器设定图
# ---------------------------------------------------------------------------
# 道具版面一式——**一式一张样板**，与 `_TEMPLATES["prop"]` 逐条对应（守卫
# test_sheets）。结构三视式对长条形物件（剑/杖/枪）是唯一清楚的画法：等大并列
# 才比得出剑身长度与护手宽度的比例关系；体积物件（碗/箱/球体）在等大三视下
# 失去主视图层次，由细节框补交代——这是版面只此一式的已知代价，换来的是契约、
# 样板与守卫的一一对应。不设色板槽位（与角色表同判据：色值信息就在主体像素里，
# 色板是索引不是像素锚）。
PROP_LAYOUTS = (
    ("结构三视式",
     "上部约三分之二区域为正面 / 侧面 / 背面三视，等高等大横向并列；"
     "下部约三分之一区域为横向一排三个局部细节框"),
)


def prop_rules(is_weapon: bool = False) -> list[str]:
    return [
        ("武器设定图 weapon design sheet" if is_weapon else "道具设定图 prop design sheet")
        + "，纯图片设定图，版面为"
        + "；".join(f"**{name}**——{spec}" for name, spec in PROP_LAYOUTS)
        + "。换道具只替换主体、版面骨架不变；"
          "所有槽位位置规整、互不重叠、彼此留出均匀空白",
        # 完整视图的硬约束：失败形态是「主体斜置出画、剑尖被裁在画外」——
        # 一张连主体都没交代完整的设定图，后续每一镜都拿不到可靠的外观基准。
        "**完整视图**：正面 / 侧面 / 背面三张定位视图一律摆正——竖直或水平对齐、"
        "不倾斜，各自**完整置于所属槽位正中，完整入画、四周留白、"
        "绝不被画面边缘裁切**、不挤压相邻槽位",
        # 等比约束：对应角色全身像那条「同一地平线、等高等比例」——缺这一条，
        # 模型会把长剑的侧视画成一把短剑，比例一失真，设定图就失去了参照价值
        "三个视图画的是**同一件物品**，"
        "长宽比例、各部位相对尺寸与结构比例严格一致，只改变观察角度；"
        "**每个观察角度只画一次、绝不重复同一角度**；"
        "不许把长剑画成短剑、把细长器物画成粗短器物",
        "结构与工艺细节清晰（纹理/磨损/接缝/机构），"
        "**局部细节框**：下部一排三个等大细节框整齐排布，每框一个关键局部的放大特写"
        "（材质/接缝/机构/铭纹），"
        "每框完整容纳其局部、不跨框不压线不与完整视图重叠——"
        "**细节框只画局部放大、完整视图只画整体全貌，两者职责不许混淆**",
        # 品类词（便利店纸杯、饮料罐、手机）会把模型拉向训练集里最强的那个真实
        # 品牌，画出可辨认的仿标；商标既是发布风险，也会撞图像与视频侧的 IP 审核
        "物品自身的标识、印花与包装文字一律为**虚构的中性图形**：不得模仿任何"
        "真实品牌的商标、名称或标志，标识内不含可读文字或字母",
        # 不设色板槽位：负面禁令必须显式在（模型照设定集惯例会自己补一条色带）
        "**画面上不出现色板色块、颜色条带或任何颜色索引行**——配色信息由主体本身呈现",
        "均匀漫射光无投影，纯色浅灰底，专业设计稿版式；"
        "整张图是完整的纯图片设定图，**禁止任何文字、标题、简介、信息栏、编号、数字、"
        "logo、水印或签名**",
    ]


def prop_sheet_prompt(p: dict, prefix: str, *, n_templates: int = 0) -> str:
    return join_prompt([prefix,
                  (template_role("prop") if n_templates else ""),
                  p.get("desc") or p.get("name") or "",
                  *prop_rules(p.get("kind") == "weapon")])


# ---------------------------------------------------------------------------
# 三、场景设定图：基准图（成品画面）+ 俯视布局图（空间图纸），成对出图
# ---------------------------------------------------------------------------
def scene_rules() -> list[str]:
    """场景基准图的版式纪律——**与角色/道具的设定图分家**。

    角色与道具要多视图和细节框：后续每一镜靠它们对形制，多一个观察角度就多一分
    一致性。场景不是这个用法——它被整张挂进分镜当光线与陈设基准（`scene_ref` /
    `scenes[].sheet`），画面里多出来的小图会连同场景一起被当作画面内容参考。

    **措辞不能带 sheet**。说「场景美术设定图 environment concept sheet」
    时，模型按美术设定集的惯例在底部补一条材质特写缩略图带（一张大图 + 五格局部
    放大），那条带子随后作为参考图进入每一镜。名称与版式同源，光在后面写「一张
    完整画面」压不住前面那个词，得连名字一起换掉，再用一条显式禁令兜住。
    """
    return [
        "场景基准图 environment key frame，广角建立镜头，无人物",
        # 正反两说：只写正面的「单幅」压不住设定集惯例，负面枚举逐词对着实测
        # 见过的泄漏形态（底部缩略图带最常出现）
        "**整幅就是一个连续画面**：单幅满幅构图 single full-bleed frame，"
        "画面不切分、不加边框、不留分格；"
        "**不出现任何局部特写小图、细节放大框、底部缩略图带、多格版面或拼贴**"
        "（no inset panels, no detail crops, no thumbnail strip, "
        "no multi-panel layout, no collage）——"
        "材质与工艺就在这一幅画面里如实呈现，不另开小图交代",
        "明确的主光方向与时段氛围（后续分镜以此为光线与陈设基准）",
        "空间纵深清晰，前中远三层景物层次分明",
        "关键陈设与材质基调明确（地面/墙面/标志性道具的质感可辨），"
        "整体色调统一可作全片色彩基准，无文字标注",
        # 基准图会整张挂进每一镜当陈设基准：门开着、灯亮着这类动作态会被逐镜继承
        "陈设取默认静止状态（门窗关合、可开合物件闭合、无人无动作），动作态留给各镜自行描述",
    ]


def scene_sheet_prompt(scene: str, prefix: str) -> str:
    """场景基准图完整提示词。

    **不收 `n_templates`**（角色与道具那两个函数收）：`_TEMPLATES` 里没有 scene 档，
    场景请求恒不附样板，而 `template_role` 讲的全是版面分区、标注栏与细节格——
    那正是这张图要避开的东西。留一个只能把版式说回去的参数是给下一个人挖坑。"""
    return join_prompt([prefix, scene, *scene_rules()])


# —— 场景俯视布局图 ——————————————————————————————————————————————————
# 一个场景两张图，各交代一半：**基准图**说这地方看上去什么样（透视画面、光线与
# 陈设基调），**俯视布局图**说这地方怎么摆（墙体边界、出入口、高差、陈设占地与朝向、
# 可通行范围）。两张都在，模型才同时拿到外观与空间两组约束——只给基准图时，模型对
# 「镜头此刻站在屋里哪个位置、人物互相在左还是在右」没有任何依据，运镜一动空间就重新编一遍。
# 故俯视图与基准图**恒成对生成**，裸 `project refs` 就出、不可关闭；
# 视频请求侧受附图配额约束，每镜只附该镜主场景的那一张（判据在 `lineage.primary_layout_ref`）。
#
# **画风跟项目走，观察方式不跟**——这两件事必须拆开说，拆不开就必然二选一错一个：
#   · 整条画风前缀都不取、只给一条固定的「扁平矢量制图」声明不行。实测产出
#     长成纸纹手绘水彩：既没执行那条固定声明，也与同项目的场景基准图不成套
#     （写实 3D CG 项目里两张图并排看不像一家的东西）。
#   · 直接整条照收也不行：画风前缀的正文里混着**渲染指令**（写实 3D CG 渲染 /
#     电影级 PBR 材质 / 柔和三点布光 / 浅景深），照单执行就是一张三维鸟瞰渲染——
#     有天花板、有透视、有投影，正是这张图唯一要避开的形态。
# 故画风照收，紧跟一句把它的**适用范围**钉死（同 `template_role` 的职责声明制度：
# 参考照给，取什么不取什么另说）。分派口在 `prefix_for`，三条生成路径共用。
TOPVIEW_MEDIUM = (
    "场景俯视布局图 set floor plan / blocking diagram，一张**正交平面制图图纸**："
    "线条稿配平涂色块，无三维渲染、无材质贴图、无投影、无景深"
)


def topview_style_clause() -> str:
    """画风职责声明——**紧跟项目画风前缀**（提示词第 2 句）。

    位置与 `template_role` 同理：声明与被声明的东西隔得越远，锚定力越弱。画风前缀里
    的渲染词与本图的投影方式正面冲突，这句话必须贴着它说。
    """
    return (
        "【画风职责·务必严格区分】以上画风**只决定本图的线条质感、上色方式与配色语言**"
        "——本图与本项目的场景基准图是同一套视觉语言下的两张图，"
        "笔触与配色要一眼看得出是一家；"
        "**画风绝不决定观察方式**：其中若含三维渲染、材质、布光、景深、镜头一类的词，"
        "一律不适用于本图——本图恒是一张**没有透视的正交平面制图**，"
        "不是被渲染出来的三维空间，也不是一张照片")


# 图纸只交代空间本身：墙体、洞口、高差、陈设的占地与朝向、可通行范围。
# 机位、视野锥、动作轴线、人物站位与走位路线属于「这一场戏」，而取景地跨场次复用；
# 固化进场景级资产等于给所有用到它的镜头强加同一套调度，换一场戏即失效。
def topview_rules() -> list[str]:
    """场景俯视布局图的版式纪律（生成与改造共用）。"""
    return [*_topview_base(), *_topview_space_only()]


def _topview_base() -> list[str]:
    """空间属性那一半——任何一场戏拿去都成立，故恒在。"""
    return [
        # ① 投影锁。「俯视」二字压不住鸟瞰渲染这一形态——它同样满足「从上往下看」，
        #    只是带着透视与天花板。英文否定词逐条对着已知的退化形态写。
        "九十度正上方垂直俯视 nadir view，正交投影 orthographic：全图没有透视收敛、"
        "没有消失点、没有镜头畸变，现实中平行的边在图上仍然平行"
        "（not isometric, not axonometric, not a 3D bird's-eye render, "
        "not a tilted aerial photo, no perspective, no vanishing point）",
        # ② 掀顶。正俯视一栋建筑得到的是屋顶——不显式掀顶，室内布局一格都看不见。
        #    1.2 米剖切高度是建筑平面图的通行惯例：这个高度切下去，门窗洞口在剖面里，
        #    桌椅床柜完整可见，而吊灯与横梁不挡视线。
        "**掀顶** roofless cutaway：屋顶、天花板与顶棚整体移除，室内一览无余；"
        "按建筑平面惯例在离地约 1.2 米处水平剖切——该高度以下的墙体、门窗洞口、"
        "家具与地面全部如实可见，之上的吊灯、横梁与阁楼一律不画；"
        "室外场景取无遮挡的正上方视角，树冠与雨棚画成半透明、不遮住其下的地面",
        "墙体与洞口按制图惯例画：被剖到的墙画成实心深色断面、厚度真实且首尾闭合，"
        "空间边界完整不留豁口；门画成墙上的缺口加一道四分之一圆弧标明开启方向；"
        "窗画成墙上的两条细平行线；台阶与高差画成等距条纹并配一个指向高处的箭头",
        # ③ 陈设的投影形态。不写死，模型会在平面图里塞进立面小图标（一把画成侧视的椅子），
        #    那种图既读不出朝向也读不出占地。
        "主要家具与地标陈设一律画**从正上方看到的真实轮廓**（桌面的矩形、椅子的坐面与"
        "椅背朝向、床的枕头端、柜子的开门面），按真实相对尺寸与真实方位摆放；"
        "**不画立面图标、不画透视小图、不画任何斜视角的家具**",
        # ④ 方位与尺度。全项目共用一条朝上约定，多个场景的平面图才能并排读；
        #    尺度参照物取人体占地圆而不是比例尺条——后者必然带数字，与无文字纪律冲突。
        "方位与尺度锚定：画面正上方恒为该场景的主入口方向（无明确入口时取主景所在的那一侧），"
        "同一项目每张俯视图共用这一条约定；图面一角放一个直径约合半米的实心圆作人体占地"
        "尺度参照，其余物件的大小一律与它可比",
        # ⑤ 可通行范围是空间事实，走位是场次属性——只做色块区分，不画路线。
        "可通行地面与被陈设占满的区域用深浅不同的平涂色块区分，一眼可辨；"
        "**不画任何路线**——不画通行路径、不画箭头、不画动线",
        # ⑥ 图签栏/指北针/比例尺是制图惯例里三个必然带文字的构件，逐个点名否掉——
        #    只写「无文字」时模型照惯例把它们补上，再在里面填一行糊字。
        "满幅单张平面图：不分格、不加边框、不加图签栏与标题栏、不画指北针玫瑰、不画比例尺条；"
        "**全图不出现任何文字、字母、数字、图例、房间名、尺寸标注或色号**"
        "——一切区分只靠颜色、线型与图标（无文字标注）",
        "层级分明：墙体断面最重、陈设次之、地面色块最轻；"
        "线条干净、留白充足，信息密度高而不乱",
    ]


def _topview_space_only() -> list[str]:
    """排除项。必须逐类点名：只声明「只画空间」压不住制图惯例，模型会按平面图的
    常见样式补上相机图标、视野锥与动线箭头。"""
    return [
        "**本图只画空间本身，不画任何拍摄或调度信息**："
        "不画机位、不画相机图标、不画视野锥或视线扇形、不画镜头标注；"
        "不画动作轴线（180° 线）、不画人物站位标记、不画走位或通行的路线与箭头；"
        "不画写实人物——谁站哪、面朝谁、镜头架在哪，随每一场戏而变，"
        "不属于这个空间本身",
    ]


def topview_ref_role() -> str:
    """俯视布局图的参考图职责声明——**只在真附上该场景基准图时注入**。

    两张图必须是同一个空间，否则视频请求里同时挂着两份互相矛盾的空间证据。让它们
    对齐的唯一可靠办法是把基准图当参考发进来；而参考图一旦在场，就必须声明用途
    边界——基准图是有透视有光影的成品画面，不声明边界时模型会照抄它的视角，
    产出的又是一张鸟瞰渲染。措辞与 `template_role` 同制度：点名是哪张、说清取什么、
    逐维否掉不取什么。"""
    return (
        "【参考图职责·务必严格区分】所附的**第一张图是本场景的基准图**"
        "（同一个地方的成品画面，有透视），两件事以它为准："
        "① **这个空间里到底有什么**——墙体与出入口的位置关系、窗的朝向、"
        "主要家具与地标陈设的种类数量与相对方位；"
        "② **画风与配色语言**——本图与它是同一个项目的一对图，"
        "笔触、色彩基调与材质感要看得出是一套；"
        "**唯独视角不许取**：参考图是斜着看的画面，本图是垂直向下看的图纸，"
        "**绝不复刻它的机位、透视、景深与光影投射方向**——"
        "不要把它重画一遍，也不要把它的构图旋转成俯视；"
        "参考图里被前景遮住或超出画幅的部分，按其空间逻辑合理补全"
    )


def scene_topview_prompt(scene: str, prefix: str) -> str:
    """场景俯视布局图完整提示词。

    `prefix` = 项目画风前缀（与其余五个构建器同一个入参）。它经 `prefix_for` 补上
    画风职责声明与图纸类型声明——**别绕过 `prefix_for` 自己拼**：裸接画风前缀就是
    让模型拿渲染指令去画平面图，产出一张三维鸟瞰渲染。

    正文恒含参考图职责声明：该场景的基准图是本图唯一的空间取材，**没有它就不该发这个
    请求**（判据在 `cli.cmd_gen_refs` 的第二波：基准图不在盘就不排计划）。
    """
    return join_prompt([prefix_for("topview", prefix), topview_ref_role(),
                        scene, *topview_rules()])


# ---------------------------------------------------------------------------
# 四、扩展设定图（opt-in·`project refs --expressions/--poses`）
# ---------------------------------------------------------------------------
# 两张扩展图共同的存在理由：主设定图（三区两视/结构三视/key art）锁的是「长什么样」，
# 扩展图锁的是「怎么演」——表情表给 dubbed/native 的表演一致性供参照（给模型看
# 「这个角色笑起来长什么样」比在提示词里描述有效），动作表给关键姿态供参照。
# **不进每镜自动挂载**（design_refs 有 8 张硬上限，多挂会挤掉主设定图）——
# 关键镜要用时显式写 `shots[].refs` 指向它，或供人工审片对照。
# 场景俯视布局图不属本节（规格在第三节）：它随每镜的视频请求发出，存在理由与消费
# 路径都与「按需追加的表演参考」不同族。
# 消费 `required_emotions`/`required_actions`：登记过的排在网格前列，缺额用
# 默认集补满——这两个字段由此获得第二个引擎消费点（第一个是 lint 覆盖度）。

# 默认表情集（4×3=12 格）：刻意把四对「差一档/易混淆」的表情排进同一张表——
# 强度差与判据差正是这张表的价值（只给孤立表情，模型每次都画成同一张微笑脸）。
EXPRESSION_SET: tuple[str, ...] = (
    "平静", "浅笑", "大笑", "悲伤",
    "哭泣", "愤怒", "惊讶", "惊惧",
    "疑惑", "冷漠", "羞赧", "坚毅")

# 默认动作集（5×3=15 格）：覆盖位移/姿态/交互/对抗四类，含足量中间态。
POSE_SET: tuple[str, ...] = (
    "站立", "行走", "坐姿", "蹲身", "奔跑",
    "回身", "抬臂指向", "俯身拾物", "挥手", "跪地",
    "后仰闪避", "跃起", "跌倒撑地", "攻击", "防御")


def _grid_fill(required, default_set: tuple, cap: int) -> list[str]:
    """网格条目合并：登记项（required_*）优先，默认集补满到 cap，逐项去重。"""
    out: list[str] = []
    for x in (required if isinstance(required, list) else []):
        s = str(x or "").strip()
        if s and s not in out:
            out.append(s)
    for s in default_set:
        if len(out) >= cap:
            break
        if s not in out:
            out.append(s)
    return out[:cap]


def expression_rules() -> list[str]:
    """表情设定图的版式纪律（生成与改造共用）。"""
    return [
        "角色表情设定图 character expression sheet，版面等分为 4 列 3 行共 12 格"
        "整齐网格，每格一个头肩特写、完整画在自己格内，格与格之间留出均匀空白",
        "十二格是**同一个角色**：五官、发型、瞳色、肤色与领口服饰完全一致，"
        "全部取同一朝向（正面微侧）、同一头身比例、同一机位高度——"
        "**只有面部表情不同，其余一切不变**",
        # 失败形态（与主设定图色板同族）：模型爱用「换个发饰/调个光/抬只手」来表演
        # 情绪，表就废了——表情表只许动脸。
        "**表演只发生在面部**：发型、衣着、饰品、光线与背景在十二格里一格不变，"
        "手也不入画——情绪全部由眉、眼睑、瞳孔高光、鼻翼、嘴角与咬肌的变化承担",
        "同族表情必须拉开强度差：浅笑只动嘴角、大笑开口见齿且眼睛眯起——"
        "相邻强度画成一样，这张表就失去了参照价值",
        "容易画混的几对，逐对钉死可见差异：平静的眼睑自然放松、冷漠的上睑略压且"
        "视线越过对方；惊讶是眉毛整体上抬、眼睁大、下颌自然落开，惊惧是眉心锁死、"
        "下眼睑绷起、嘴向两侧水平绷平；悲伤眼眶泛红而无泪，哭泣有泪光且呼吸带动肩线",
        "均匀漫射柔光无投影，纯色浅灰无缝底，专业表情参考表版式，无场景干扰无文字标注",
    ]


def expression_sheet_prompt(c: dict, prefix: str) -> str:
    """角色表情设定图完整提示词。网格条目 = required_emotions 优先 + 默认集补满。"""
    items = _grid_fill(c.get("required_emotions"), EXPRESSION_SET, 12)
    parts = [prefix,
             *expression_rules(),
             c.get("appearance", ""),
             (f"发型：{c['hair']}" if c.get("hair") else ""),
             "十二格表情从左到右、从上到下依次为：" + "、".join(items)]
    return join_prompt(parts)


def pose_rules(gear: str = "") -> list[str]:
    """动作设定图的版式纪律（生成与改造共用）。"""
    return [
        "角色动作设定图 character pose sheet，版面等分为 5 列 3 行共 15 格整齐网格，"
        "每格一个**全身**动作、完整画在自己格内不被格线裁切，格与格之间留出均匀空白",
        "十五格是**同一个角色**：身形、发型、服装与配色完全一致，同一比例——"
        "只有动作不同",
        figure_proportions(),
        # 差异锁：动作表最常见的废图是「十五格站桩微调」——逐格钉死剪影可辨。
        "**每格动作的剪影必须可区分**：任意两格不得是同一姿势的镜像或微调；"
        "带过程的动作一律取**进行中的中间态**"
        + (f"（如「{gear}」出鞘，画拔到一半、鞘口仍咬着刃身的那一瞬，"
           f"而不是拔完之后的持械亮相）" if gear
           else "（如拾物，画俯身指尖将触未触的那一瞬，而不是直立提物的结果）"),
        "动力结构真实：奔跑有前倾与摆臂、跃起双脚与地面有清晰间隙、"
        "攻击画出转腰送肩的力量传递、防御画出重心下沉的承力结构、"
        "跌倒有手撑地的受力反应；坐姿配一只无装饰的素色方凳，"
        "衣料贴着凳面自然压出褶皱、不与凳体穿插",
        "正交平视视角，均匀漫射柔光无投影，纯色浅灰无缝底，"
        "专业动作参考表版式，无场景干扰无文字标注",
    ]


def pose_sheet_prompt(c: dict, prefix: str) -> str:
    """角色动作设定图完整提示词。网格条目 = required_actions 优先 + 默认集补满。
    角色有武器时对抗类动作持械（这张表管「怎么演」，与主设定图「全身空手」不冲突
    ——那是身份定稿底图，这是表演参考）。"""
    gear = str(c.get("weapon") or "").strip()
    items = _grid_fill(c.get("required_actions"), POSE_SET, 15)
    parts = [prefix,
             *pose_rules(gear),
             c.get("appearance", ""),
             (f"服装：{c['outfit']}" if c.get("outfit") else ""),
             (f"发型：{c['hair']}" if c.get("hair") else ""),
             (f"对抗类动作（攻击/防御）持其武器「{gear}」表演" if gear else ""),
             "十五格动作从左到右、从上到下依次为：" + "、".join(items)]
    return join_prompt(parts)


