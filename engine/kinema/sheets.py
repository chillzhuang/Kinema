"""设定图规格与版式规则 —— **每种设定图「长什么样」的单一真源**。

## 为什么必须是单一真源

设定图有三条会走到的生成路径：

  · `project refs`（首次出图 / `--force` 整张重出）
  · `refine --asset`（灯箱局部改造：框选一块改）
  · Studio 灯箱「↻ 重新生成」

它们要产出的**是同一张规格的图**。规则一旦只写在其中一条路径里，另外两条就只剩
「旧图 + 一句话指令」——模型没有版式约束，改完就跑偏。失败形态：角色设定图局部
改造后，**分区版式塌了、还被按 1:1 出成方图**（refine 里写死
`"1:1" if kind != "scene"`，而角色本该是 16:9 横版）。

所以本模块同时管两件事，缺一不可：

  1. **`aspect_for`** —— 该类设定图的画布比例（角色 16:9 三区横版 / 道具 1:1 /
     场景跟随项目比例）。尺寸错了，版式无从谈起。
  2. **`rules_for`** —— 该类设定图的完整版式纪律（三区两视铁律 / 三视等大不裁切 /
     无色板无场景无文字…）。局部改造把它一并喂回去，模型才知道
     "这张图本来该长什么样"。
"""
from __future__ import annotations

from pathlib import Path

from .project import DEFAULT_ASPECT

# 画布比例：改这里就是改全部三条路径（任何一条路径本地写死一份就是分叉的来源）
# expression/pose 是网格表（4×3 / 5×3），topview 是横幅平面图——三者恒 16:9。
# topview 不跟随项目比例（scene 跟随）：它是图纸不是画面，竖屏项目把平面图压成
# 9:16 只会让横向的空间关系挤成一条，读不出左右站位。
# 兜底比例引用引擎单源常量（project.DEFAULT_ASPECT），不本地写死一份。
_ASPECT = {"character": "16:9", "prop": "1:1", "weapon": "1:1",
           "expression": "16:9", "pose": "16:9", "topview": "16:9"}


# ---------------------------------------------------------------------------
# 版式样板图（骨架参考图）——引擎内置资产，生成设定图时自动垫在参考图最前
# ---------------------------------------------------------------------------
# char_rules/prop_rules 的版式纪律很精确，但纯文字描述的执行率不稳定（色板被画成
# 缩略图墙、三视挤成一团、色板横跨全幅底部）。版式靠垫图，不靠文字复述。
#
# 每类**一张素描线稿样板**：铅笔素描画在纯白纸面上（与简笔板样板同一素描语言），
# 主体去身份、无配色。素描样板几乎没有内容可抄，单张即可教版式。
#
# 三条设计约束（缺一条就会从「教版式」变成「教内容」）：
#   ① **样板必须去身份**（角色=无五官的关节素体人台，道具=中性示意物）：
#      样板主体占住交代形体的那些槽位，示范的是位置与尺度，不是内容。
#   ② 生成时必须同时注入 `template_role` 职责声明——去身份消掉了内容继承面，
#      画风/**媒介**维度的越界参考仍要靠它压：素描是强烈的 2D 手绘信号，媒介统一
#      条款在素描样板下尤其要硬。长相条款作兜底恒在（守卫 test_adapt）。
#   ③ 样板自身不带画风前缀——画风由每次生成的 style_prefix 决定。
# 缺文件时静默降级：提示词已完整描述版式，样板只压方差。
TEMPLATE_DIR = Path(__file__).resolve().parent / "assets" / "blueprints"
# **只有带分区版式的设定图才配样板**：角色是三区两视定稿表、道具是结构三视表，
# 版式复杂到值得用图去教。**场景刻意没有样板**——它是单幅环境 key art
# （广角建立镜头），压根没有分区结构可学，垫一张具体的空间只会把它的陈设与光线
# 污染进每一张场景图（垫具体空间的产出就是一张普通空房间照片）。
_TEMPLATES = {
    "character": ("char_template.png",),
    "prop": ("prop_template.png",),
}

# 职责声明**必须紧跟画风前缀**（提示词第 2 句）而不是埋在版式规则之后：样板图带着
# 完整的画风信息，而画风声明与"别学画风"这句隔着二十几句版式规则时，前者的锚定力
# 会被稀释——模型很容易把样板当成画风垫图。
# 措辞三件套缺一不可：**点名是第一张图**（同时有 moodboard 垫图时不至于混淆）、
# **画风归属明确回指开头**、**给它一个身份**（"版面结构示意图"而非"参考作品"）。
# 蓝图只含纯图形布局，产出同样是纯图片——两侧都无文字，故声明里的文字条款是
# 一条单向禁令（别自己补字），而非「样板上的字别抄」。
#
# 两类样板只在一处措辞上分家：各槽位该被什么填满。共用一套文案，
# 角色提示词里就会讲到道具的版面。
_ROLE_WORDING = {
    "character": {
        "slots": "左区肖像槽位是该角色的锁骨以上正面特写，中区与右区分别是他的"
                 "正面与背面全身立像",
    },
    "prop": {
        "slots": "上部三视槽位是该物件摆正的整体全貌，下部细节框是它的局部放大",
    },
}


def template_role(kind: str = "character") -> str:
    """样板职责声明（每类样板恒为单张，调用方按实附与否决定注入）。

    核心裁决：样板**只准参考布局**——版面分区、各区位置与比例关系；画风与内容
    的裁决权全部交还给开头的风格描述与下文的对象描述。
    """
    w = _ROLE_WORDING[kind]
    return (
        "【参考图职责·务必严格区分】所附参考图中的**第一张是版式样板图**，"
        "唯一用途是对齐**版面分区、各区的位置与比例关系——只准参考布局**；"
        "**样板的画风、笔触、上色方式、配色、人物与物件一律与本图无关，"
        "严禁参考、严禁复刻、严禁沿用**——本图的画风**只以开头的风格描述为准**，"
        "画面内容只以下文描述的对象为准；"
        # ↓ 长相条款：泛称「人物」压不住脸。带脸样板会把"脸"教成版式的一部分
        #   （黑发白袍少年会被画成样板那张女性面孔）。无五官线稿样板下这条
        #   只是兜底——换用带脸主体时它是唯一的拦截点，故不撤。
        # 禁令的宾语必须收窄到具体维度：写成「一笔都不许从样板取材」再补一句例外，
        # 两句相邻打架，模型只执行更强的那条。先划边界，再正面给出可对齐项
        + ("**尤其是样板上那个人台**：脸型、五官、发型、性别、年龄感、体型胖瘦"
           "**这几维一律只按下文的角色描述画，一笔都不许从样板取材**；"
           "**可以且只可以对齐它的水平定位线高度**——人台的胯线落在头顶到脚底的"
           "正中或略高于正中，成品两个全身立像照此对齐；"
           if kind == "character" else "")
        + "样板中的线稿轮廓、空框与占位图形只是纯图形版式占位，不是成品内容，绝不原样复刻；"
        f"成品各槽位一律用对象本身的图像填满——{w['slots']}；"
        "整张设定图不生成标题、简介、信息栏、编号、尺寸数字、色号或任何其他文字。"
        "请把样板当作纯图片版面结构示意图看待，它不是画风垫图、也不是内容参考。"
        # ↓ 媒介统一条款：样板图必然带着自己的媒介（黑白铅笔素描——强烈的 2D
        #   手绘信号），而"别学画风"若不点名**媒介**这一维，模型仍会把 2D/3D
        #   这件事从样板上抄走——风格前缀缺媒介锚点时，设定图会被样板带离
        #   项目媒介，同项目两种媒介并存。故此句必须在。
        "**尤其是媒介维度**：样板是一张黑白铅笔素描，而素描不是本图的媒介——"
        "**绝不把成品画成线稿、素描、涂鸦或未上色草图**；"
        "本图的媒介只由开头风格描述里的媒介词（如「写实 3D CG 渲染」「2D 手绘动画」）决定，"
        "并且必须与本项目其余全部产出（其他角色设定图、场景图、道具图、分镜图、封面）"
        "保持**同一种媒介、同一套画风语言**，绝不允许同一项目内一张 2D 一张 3D")


def join_prompt(parts) -> str:
    """把版式条目与作者字段拼成一条提示词——**设定图提示词的唯一拼装口**。

    本模块六个提示词构建器与 `refine.refine_asset` 都走这里，分隔符只由它补：
    条目自带句尾逗号会叠成「，，」，作者字段只含空白会拼出孤立的空段。两者都不报错、
    也不会被任何版式断言看见，只是在千余字的提示词里多出几处断句噪声，稀释相邻那条
    硬约束的权重。故统一 strip 掉首尾空白与尾随分隔符后再丢空。
    """
    return "，".join(s for s in (str(x or "").strip().rstrip("，、；;,") for x in parts) if s)


def templates_for(kind: str) -> list[Path]:
    """该类设定图的版式样板图（只返回在盘的，缺文件静默降级为空列表）。"""
    return [p for name in _TEMPLATES.get(kind, ())
            if (p := TEMPLATE_DIR / name).is_file()]


def aspect_for(kind: str, series=None) -> str:
    """该类设定图的画布比例。场景图跟随项目比例（它是全片的光线与陈设基准，
    比例不同构图就不同），其余按类型定死。"""
    if kind == "scene":
        return (series.data.get("aspect") if series else None) or DEFAULT_ASPECT
    return _ASPECT.get(kind, DEFAULT_ASPECT)


def prefix_for(kind: str, style_prefix: str) -> str:
    """该类设定图提示词的开头声明——与 `aspect_for` 同制度的单一真源，
    `project refs` / `refine --asset` / 灯箱重生三条路径共用。

    俯视布局图在项目画风之后多两句：**画风职责声明**（画风只管线条与配色、不管
    观察方式）+ **图纸类型声明**。判据见 `TOPVIEW_MEDIUM` 上方。其余各类一律裸用
    项目画风前缀。"""
    if kind != "topview":
        return style_prefix
    return join_prompt([style_prefix, topview_style_clause(), TOPVIEW_MEDIUM])


