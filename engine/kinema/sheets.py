# 五、给局部改造用的「规则回喂」
# ---------------------------------------------------------------------------
def rules_for(kind: str, holder: dict | None = None) -> list[str]:
    """该类设定图的版式纪律（不含该实体的具体描述）。

    局部改造必须把这一段喂回去：只给「旧图 + 改哪儿改什么」，模型不知道这张图
    本来该是三区/三视该等大/全身该空手，改完版式就塌了。
    """
    h = holder or {}
    if kind == "character":
        return [*char_rules(), *char_tail()]
    if kind in ("prop", "weapon"):
        return prop_rules(h.get("kind") == "weapon" or kind == "weapon")
    if kind == "scene":
        return scene_rules()
    if kind == "expression":
        return expression_rules()
    if kind == "pose":
        return pose_rules((h.get("weapon") or "").strip())
    if kind == "topview":
        return topview_rules()
    return []
